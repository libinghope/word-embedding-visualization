import { test, expect } from '@playwright/test'
test('bridge search, projection invariance, exchange, OOV and clear', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.statusbar')).toContainText('1,000 WORDS')
  await page.getByRole('button', { name: '连接探索', exact: true }).click()
  await page.getByLabel('领域 A', { exact: true }).fill('water')
  await page.getByLabel('领域 B', { exact: true }).fill('energy')
  await page.getByRole('button', { name: '寻找桥梁' }).click()
  const table = page.getByTestId('bridge-results')
  await expect(table.locator('tbody tr')).toHaveCount(20)
  await page.screenshot({ path: '../docs/screenshots/bridges.png', fullPage: true })
  const before = await table.innerText()
  await table.locator('button').first().click()
  await page.getByRole('button', { name: 'PCA', exact: true }).click()
  expect(await table.innerText()).toBe(before)
  const word = await table.locator('button').first().innerText()
  await page.getByRole('button', { name: '交换 A/B' }).click()
  await page.getByRole('button', { name: '寻找桥梁' }).click()
  await expect(table.locator('button').first()).toHaveText(word)
  await page.getByLabel('领域 A', { exact: true }).fill('not_in_vocabulary')
  await page.getByRole('button', { name: '寻找桥梁' }).click()
  await expect(page.getByRole('alert')).toContainText('未收录')
  await page.getByRole('button', { name: '清空领域' }).click()
  await expect(page.getByLabel('领域 A', { exact: true })).toHaveValue('')
  await expect(table).toHaveCount(0)
})
